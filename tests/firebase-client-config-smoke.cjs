'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const config=JSON.parse(read('app/src/release/google-services.json'));
const project=config.project_info;
const clients=config.client||[];
const registered=clients.filter(c=>c.client_info?.android_client_info?.package_name==='ir.kanonha.app');
assert.equal(registered.length,1,'Exactly one registered production Android client expected');
assert.equal(project.project_id,'kanonha-86f00');
assert.equal(project.project_number,'172921153592');
assert.equal(registered[0].client_info.mobilesdk_app_id,'1:172921153592:android:ffd6bec6daf6f9f5a7decd');
assert.equal(registered[0].api_key?.length,1);
assert.match(registered[0].api_key[0].current_key,/^AIza[A-Za-z0-9_-]+$/);
assert.deepEqual(registered[0].oauth_client,[]);
assert.equal(config.configuration_version,'1');
assert.doesNotMatch(JSON.stringify(config),/private_key|service_account|client_email/);
const rootGradle=read('build.gradle.kts');
const appGradle=read('app/build.gradle.kts');
assert.ok(rootGradle.includes('id("com.google.gms.google-services") version "4.6.0" apply false'));
assert.ok(appGradle.includes('id("com.google.gms.google-services")'));
assert.ok(appGradle.includes('versionCode = 46'));
assert.ok(appGradle.includes('versionName = "0.9.33-membership-approval"'));
assert.ok(appGradle.includes('processDebugGoogleServices'));
assert.ok(appGradle.includes('enabled = false'));
assert.ok(appGradle.includes('firebase-bom:35.2.0'));
assert.ok(appGradle.includes('implementation("com.google.firebase:firebase-messaging")'));
assert.ok(!fs.existsSync(path.join(root,'app/src/debug/google-services.json')));
const push=read('app/src/main/java/ir/kanonha/app/KanonhaFirebasePush.java');
assert.ok(push.includes('BuildConfig.DEBUG'));
assert.ok(push.includes('FirebaseApp.initializeApp(context)'));
assert.ok(push.includes('options.getProjectId()'));
assert.ok(push.includes('options.getApplicationId()'));
assert.ok(push.includes('options.getGcmSenderId()'));
assert.ok(push.includes('setAutoInitEnabled(false)'));
assert.ok(push.includes('getToken().addOnCompleteListener'));
assert.ok(push.includes('native.confirmOwner')===false);
assert.ok(!push.includes('BuildConfig.FCM_API_KEY'));
const manifest=read('app/src/main/AndroidManifest.xml');
assert.ok(manifest.includes('firebase_messaging_auto_init_enabled'));
assert.ok(manifest.includes('android:value="false"'));
assert.ok(manifest.includes('.KanonhaFirebaseService'));
console.log('PASS: Firebase official release client, correct package, Gradle plugin, privacy, SDK token flow, debug isolation');
